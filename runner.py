def _evaluate(name, state, expected, description):
    """Run one scenario and return a result record."""
    actual = decide_next_move(state)
    return {
        "name": name,
        "description": description,
        "state": state,
        "expected": expected,
        "actual": actual,
        "passed": actual == expected,
    }


def run_simulation():
    """Run all named scenarios plus the exhaustive 64-state sweep and return
    a report dictionary with the scenario results, totals and success rate."""
    results = []

    # 1. Named scenarios.
    for name, state, expected, description in NAMED_SCENARIOS:
        results.append(_evaluate(name, state, expected, description))

    # 2. Exhaustive sweep over every possible boolean state.
    for values in itertools.product([False, True], repeat=6):
        state = dict(zip(STATE_KEYS, values))
        expected = oracle(state)
        results.append(
            _evaluate(
                "exhaustive_" + "_".join(
                    "{}{}".format(
                        key[:2], 1 if value else 0
                    ) for key, value in zip(STATE_KEYS, values)
                ),
                state,
                expected,
                "Exhaustive state checked against the independent oracle.",
            )
        )

    total = len(results)
    passed = sum(1 for item in results if item["passed"])
    failed = total - passed

    failed_scenarios = [
        {"name": item["name"], "state": item["state"],
         "expected": item["expected"], "actual": item["actual"]}
        for item in results if not item["passed"]
    ]

    report = {
        "total_scenarios": total,
        "passed_scenarios": passed,
        "failed_scenarios": failed,
        "success_rate": passed / total if total else 0.0,
        "named_scenario_count": len(NAMED_SCENARIOS),
        "exhaustive_scenario_count": total - len(NAMED_SCENARIOS),
        "failures": failed_scenarios,
        "results": results,
    }
    return report


def save_report(report, path):
    """Save the simulation report to a JSON file."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, ensure_ascii=False)


def main():
    report = run_simulation()

    # Exact file name requested in the brief, plus a copy under artifacts/.
    root_path = os.path.join(HERE, "simulation_report.json")
    artifacts_path = os.path.join(ARTIFACTS_DIR, "simulation_report.json")
    save_report(report, root_path)
    save_report(report, artifacts_path)

    print("Simulation finished.")
    print("Total scenarios : {}".format(report["total_scenarios"]))
    print("Passed          : {}".format(report["passed_scenarios"]))
    print("Failed          : {}".format(report["failed_scenarios"]))
    print("Success rate    : {:.2%}".format(report["success_rate"]))
    if report["failures"]:
        print("Failed scenarios:")
        for item in report["failures"]:
            print(
                "  - {name}: expected {expected}, got {actual}".format(**item)
            )
    print("Report saved to: {}".format(root_path))


if __name__ == "__main__":
    main()
