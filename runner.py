"""
runner.py

Simulation Runner for the navigation logic.

It does not need the IR-SIM graphical environment: it feeds hand-crafted
sensor states (dictionaries with the six boolean keys) to the
decide_next_move(state) function generated by the Developer Agent and checks
the returned action against the expected action.

Two layers of coverage are provided:
    1. Named, human-readable scenarios that pin down every important
       behaviour described in the brief and the plan.
    2. An exhaustive sweep over ALL 2**6 = 64 possible boolean states,
       compared against an independent oracle that encodes the brief.

The resulting report records, for every scenario, the state, the expected
action, the actual action and whether it passed, plus totals and the success
rate (passed / total).  It is saved as simulation_report.json.

Usage:
    python runner.py
"""

import itertools
import json
import os

from generated.navigation_logic import decide_next_move

HERE = os.path.dirname(os.path.abspath(__file__))
ARTIFACTS_DIR = os.path.join(HERE, "artifacts")

STATE_KEYS = (
    "goal_ahead",
    "goal_on_left",
    "goal_on_right",
    "front_blocked",
    "left_blocked",
    "right_blocked",
)


def make_state(goal_ahead=False, goal_on_left=False, goal_on_right=False,
               front_blocked=False, left_blocked=False, right_blocked=False):
    """Build a sensor state dictionary with exactly the six boolean keys."""
    return {
        "goal_ahead": goal_ahead,
        "goal_on_left": goal_on_left,
        "goal_on_right": goal_on_right,
        "front_blocked": front_blocked,
        "left_blocked": left_blocked,
        "right_blocked": right_blocked,
    }


def oracle(state):
    """Independent reference implementation of the brief, written directly
    from the requirements text (used for the exhaustive 64-state sweep).

    Rules:
    - move toward the goal whenever that direction is not blocked;
    - otherwise keep moving through any direction that is not blocked;
    - if every direction is blocked, stop.
    """
    if state["goal_ahead"] and not state["front_blocked"]:
        return "FORWARD"
    if state["goal_on_left"] and not state["left_blocked"]:
        return "LEFT"
    if state["goal_on_right"] and not state["right_blocked"]:
        return "RIGHT"
    if not state["front_blocked"]:
        return "FORWARD"
    if not state["left_blocked"]:
        return "LEFT"
    if not state["right_blocked"]:
        return "RIGHT"
    return "STOP"


# Named scenarios: (name, state, expected action, human description).
